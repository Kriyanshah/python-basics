# break 
for i in range(100):
    if(i == 56): # if i is equal to 56 then exit the loop
        break
    print(i) # prints 0 to 55 and then breaks the loop

# continue
for i in range(100):
    if(i == 36): # if i is equal to 36 then skip the iteration and continue with the next iteration
        continue
    print(i)

