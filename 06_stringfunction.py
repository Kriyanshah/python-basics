name = "kriyan shah"

print(len(name))     # length of string
print(name.endswith("ah"))    # boolean
print(name.startswith("kr"))   # boolean
print(name.capitalize())    #capitalize first letter
print(name.upper())    # capitalize everything
print(name.lower())    #  de capitalize everything
print(name.count("a"))  # frequency of a character
print(name.title()) # capitalize first letter of every word
print(name.replace("shah", "jain")) #replace word of string
print(name.find("shah")) # find the position of word


# string are immutable